create table marcas (
  id bigint generated by default as identity primary key,
  nombre varchar(120) not null unique,
  logo_url varchar(500)
);

create table categorias (
  id bigint generated by default as identity primary key,
  nombre varchar(120) not null unique,
  slug varchar(140) not null unique
);

create table subcategorias (
  id bigint generated by default as identity primary key,
  nombre varchar(120) not null,
  slug varchar(140) not null unique,
  categoria_id bigint not null references categorias(id)
);

create table productos (
  id bigint generated by default as identity primary key,
  slug varchar(180) not null unique,
  nombre varchar(180) not null,
  marca_id bigint not null references marcas(id),
  categoria_id bigint not null references categorias(id),
  subcategoria_id bigint references subcategorias(id),
  precio numeric(12, 2) not null,
  descripcion text,
  medida varchar(60) not null,
  ancho integer,
  perfil integer,
  aro integer,
  indice_carga varchar(40),
  indice_velocidad varchar(20),
  tipo varchar(80),
  disponibilidad varchar(20) not null check (disponibilidad in ('DISPONIBLE', 'SIN_STOCK')),
  estado varchar(20) not null check (estado in ('ACTIVO', 'OCULTO')),
  ficha_tecnica_url varchar(500),
  fecha_creacion timestamp with time zone not null,
  fecha_actualizacion timestamp with time zone not null
);

create table imagenes_producto (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references productos(id) on delete cascade,
  nombre_archivo varchar(180) not null,
  ruta varchar(500) not null,
  url varchar(500) not null,
  orden integer not null check (orden between 1 and 5),
  unique (producto_id, orden)
);

create table promociones (
  id bigint generated by default as identity primary key,
  titulo varchar(160) not null,
  imagen_url varchar(500) not null,
  fecha_inicio date not null,
  fecha_fin date not null,
  estado varchar(20) not null check (estado in ('ACTIVA', 'INACTIVA')),
  check (fecha_fin >= fecha_inicio)
);

create table solicitudes_contacto (
  id bigint generated by default as identity primary key,
  nombre varchar(120) not null,
  email varchar(180) not null,
  telefono varchar(40),
  asunto varchar(160),
  mensaje text not null,
  fecha_creacion timestamp with time zone not null
);

create index idx_productos_slug_estado on productos(slug, estado);
create index idx_productos_medida_estado on productos(medida, estado);
create index idx_productos_nombre_estado on productos(nombre, estado);
create index idx_promociones_estado_fechas on promociones(estado, fecha_inicio, fecha_fin);

